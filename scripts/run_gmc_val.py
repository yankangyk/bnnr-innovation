        ("gmc_wknn_dual_all",  dict(fill="wknn", block="dual", trindex="all",
                                    wknn_k=30, wknn_r=0.95, coldstart=True)),
        ("gmc_knn_sym_all",    dict(fill="knn",  block="sym",  trindex="all",      wknn_k=10)),
