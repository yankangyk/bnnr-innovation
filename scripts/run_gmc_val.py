"""Run GMC configuration grids on the INDEPENDENT validation folds (de-leakage).

The per-dataset GMC configurations were originally selected by inspecting
the 10-fold CVa TEST results (a reviewer vulnerability: the reported folds took
part in the selection).  This script re-does the selection on validation folds
generated by ``scripts/gen_val_folds.py`` — a fresh ~10% pos+neg hold-out inside
each fold's training entries, disjoint from the reported test indices.  The
validation winner is then frozen and reported on the ORIGINAL test folds, so the
reported numbers never participate in configuration selection.

Grids (per PROGRESS.md de-leakage plan, updated for the post-Y-strengthening state):
  F / C   : the fixed block+filter pipeline (single candidate), plus a
            block-only no-filter control on F to confirm the filter earns its
            keep on unseen folds (tensor view omitted on F/C is an a-priori
            scale rule, not a tuned choice).
  CTD     : w_bnnr in {0.1,0.2,0.3} x graph-embedding {off} or {a=0.3,0.7,1.2,2.0},
            w_tensor=0.8, tensor rank-cap 200, rank fusion.  The tensor view is
            independent of the grid, so it is computed once per fold and cached.
  Y       : full factorial over the View-A switches that define the Y config:
            fill {wknn,knn} x block {sym,dual} x trindex {all,observed}.

Usage:
    python scripts/run_gmc_val.py --datasets Fdataset Cdataset       # run grids
    python scripts/run_gmc_val.py --datasets CTDdataset2023          # run CTD grid
    python scripts/run_gmc_val.py --datasets Ydataset                # run Y grid
    python scripts/run_gmc_val.py --datasets Fdataset --save-winner  # save winner val preds
"""
